/**
 * Server-side Luau runtime injected into published places (ServerScriptService/BloxRuntime).
 * It reads CollectionService tags written by the serializer and turns them into gameplay:
 * kill bricks, checkpoints with respawn, finish line with timer, disappearing tiles,
 * moving platforms and spinners (physics-driven so players ride them), plus a stage/timer HUD.
 */
export const BLOX_SERVER_RUNTIME = `-- BloxRuntime · generated by Blox Studio. Do not edit: it is regenerated on every publish.
-- Powers gameplay configured in the editor: kill bricks, checkpoints, finish line,
-- disappearing tiles, moving platforms and spinners, plus the stage/timer HUD.
local CollectionService = game:GetService("CollectionService")
local Players = game:GetService("Players")
local RunService = game:GetService("RunService")
local TweenService = game:GetService("TweenService")

local function tagArg(part, prefix)
	for _, tag in ipairs(CollectionService:GetTags(part)) do
		if string.sub(tag, 1, #prefix) == prefix then
			return string.sub(tag, #prefix + 1)
		end
	end
	return nil
end

local function numbers(text)
	local list = {}
	for value in string.gmatch(text or "", "[^,]+") do
		table.insert(list, tonumber(value) or 0)
	end
	return list
end

local function characterFrom(hit)
	local model = hit:FindFirstAncestorOfClass("Model")
	if not model then return nil end
	local humanoid = model:FindFirstChildOfClass("Humanoid")
	if not humanoid or humanoid.Health <= 0 then return nil end
	local player = Players:GetPlayerFromCharacter(model)
	if not player then return nil end
	return player, model, humanoid
end

-- Checkpoints -----------------------------------------------------------------
local checkpoints = {}
local totalStages = 1
for _, part in ipairs(CollectionService:GetTagged("BloxCheckpoint")) do
	local stage = tonumber(tagArg(part, "BloxStage=")) or 2
	checkpoints[stage] = part
	totalStages = math.max(totalStages, stage)
end

local state = {}

local function hud(player)
	local playerGui = player:FindFirstChild("PlayerGui")
	return playerGui and playerGui:FindFirstChild("BloxHud")
end

local function label(name, parent, position, size, font, color)
	local text = Instance.new("TextLabel")
	text.Name = name
	text.BackgroundTransparency = 1
	text.Position = position
	text.Size = size
	text.Font = font
	text.TextScaled = true
	text.TextColor3 = color
	text.Parent = parent
	return text
end

local function buildHud(player)
	local gui = Instance.new("ScreenGui")
	gui.Name = "BloxHud"
	gui.ResetOnSpawn = false
	local card = Instance.new("Frame")
	card.Name = "Card"
	card.AnchorPoint = Vector2.new(0.5, 0)
	card.Position = UDim2.new(0.5, 0, 0, 8)
	card.Size = UDim2.fromOffset(220, 64)
	card.BackgroundColor3 = Color3.fromRGB(17, 20, 31)
	card.BackgroundTransparency = 0.2
	card.Parent = gui
	local corner = Instance.new("UICorner")
	corner.CornerRadius = UDim.new(0, 16)
	corner.Parent = card
	local stroke = Instance.new("UIStroke")
	stroke.Color = Color3.fromRGB(255, 255, 255)
	stroke.Transparency = 0.75
	stroke.Thickness = 2
	stroke.Parent = card
	local stage = label("Stage", card, UDim2.new(0, 0, 0, 6), UDim2.new(1, 0, 0, 30), Enum.Font.FredokaOne, Color3.new(1, 1, 1))
	stage.Text = "Stage 1 / " .. totalStages
	local timer = label("Timer", card, UDim2.new(0, 0, 0, 37), UDim2.new(1, 0, 0, 20), Enum.Font.GothamBold, Color3.fromRGB(255, 214, 10))
	timer.Text = "0.0s"
	local banner = label("Banner", gui, UDim2.new(0.5, 0, 0.28, 0), UDim2.new(0.8, 0, 0, 64), Enum.Font.FredokaOne, Color3.new(1, 1, 1))
	banner.AnchorPoint = Vector2.new(0.5, 0.5)
	banner.TextTransparency = 1
	banner.TextStrokeTransparency = 1
	banner.Text = ""
	gui.Parent = player:WaitForChild("PlayerGui")
	return gui
end

local function announce(player, text, color)
	local gui = hud(player)
	local banner = gui and gui:FindFirstChild("Banner")
	if not banner then return end
	banner.Text = text
	banner.TextColor3 = color or Color3.new(1, 1, 1)
	banner.TextTransparency = 0
	banner.TextStrokeTransparency = 0.3
	local token = os.clock()
	banner:SetAttribute("Token", token)
	task.delay(2.2, function()
		if banner:GetAttribute("Token") == token then
			TweenService:Create(banner, TweenInfo.new(0.5), { TextTransparency = 1, TextStrokeTransparency = 1 }):Play()
		end
	end)
end

local function setStage(player, stage)
	local s = state[player]
	if not s or stage <= s.stage then return end
	s.stage = stage
	local stats = player:FindFirstChild("leaderstats")
	if stats and stats:FindFirstChild("Stage") then stats.Stage.Value = stage end
	local gui = hud(player)
	if gui then gui.Card.Stage.Text = "Stage " .. stage .. " / " .. totalStages end
	announce(player, "Checkpoint! Stage " .. stage, Color3.fromRGB(74, 222, 128))
end

local function onPlayer(player)
	state[player] = { stage = 1, start = os.clock(), finished = false }
	local stats = Instance.new("Folder")
	stats.Name = "leaderstats"
	local stageValue = Instance.new("IntValue")
	stageValue.Name = "Stage"
	stageValue.Value = 1
	stageValue.Parent = stats
	stats.Parent = player
	task.spawn(buildHud, player)
	player.CharacterAdded:Connect(function(character)
		local s = state[player]
		local checkpoint = s and checkpoints[s.stage]
		if checkpoint then
			local root = character:WaitForChild("HumanoidRootPart", 5)
			if root then
				task.wait()
				root.CFrame = CFrame.new(checkpoint.Position + Vector3.new(0, checkpoint.Size.Y / 2 + 3, 0))
			end
		end
	end)
end

Players.PlayerAdded:Connect(onPlayer)
for _, player in ipairs(Players:GetPlayers()) do onPlayer(player) end
Players.PlayerRemoving:Connect(function(player) state[player] = nil end)

task.spawn(function()
	while true do
		task.wait(0.1)
		for player, s in pairs(state) do
			if not s.finished then
				local gui = hud(player)
				if gui then gui.Card.Timer.Text = string.format("%.1fs", os.clock() - s.start) end
			end
		end
	end
end)

for stage, part in pairs(checkpoints) do
	part.Touched:Connect(function(hit)
		local player = characterFrom(hit)
		if player then setStage(player, stage) end
	end)
end

-- Kill bricks -------------------------------------------------------------------
for _, part in ipairs(CollectionService:GetTagged("BloxKill")) do
	part.Touched:Connect(function(hit)
		local player, _, humanoid = characterFrom(hit)
		if player then humanoid.Health = 0 end
	end)
end

-- Finish line -------------------------------------------------------------------
for _, part in ipairs(CollectionService:GetTagged("BloxFinish")) do
	part.Touched:Connect(function(hit)
		local player = characterFrom(hit)
		local s = player and state[player]
		if not s or s.finished then return end
		s.finished = true
		local elapsed = os.clock() - s.start
		local gui = hud(player)
		if gui then
			gui.Card.Timer.Text = string.format("%.2fs", elapsed)
			gui.Card.Stage.Text = "Finished!"
		end
		announce(player, string.format("You beat it in %.1fs!", elapsed), Color3.fromRGB(255, 214, 10))
		local burst = Instance.new("ParticleEmitter")
		burst.Color = ColorSequence.new(Color3.fromRGB(255, 214, 10), Color3.fromRGB(255, 90, 95))
		burst.Rate = 0
		burst.Speed = NumberRange.new(25, 45)
		burst.SpreadAngle = Vector2.new(70, 70)
		burst.Lifetime = NumberRange.new(1.5, 2.5)
		burst.Size = NumberSequence.new(0.7)
		burst.Acceleration = Vector3.new(0, -40, 0)
		burst.LightEmission = 0.6
		burst.Parent = part
		burst:Emit(150)
		task.delay(4, function() burst:Destroy() end)
	end)
end

-- Disappearing tiles ------------------------------------------------------------
for _, part in ipairs(CollectionService:GetTagged("BloxFade")) do
	local busy = false
	local original = part.Transparency
	part.Touched:Connect(function(hit)
		if busy or not characterFrom(hit) then return end
		busy = true
		TweenService:Create(part, TweenInfo.new(0.6), { Transparency = 1 }):Play()
		task.wait(0.6)
		part.CanCollide = false
		task.wait(2.5)
		part.CanCollide = true
		TweenService:Create(part, TweenInfo.new(0.3), { Transparency = original }):Play()
		busy = false
	end)
end

-- Moving platforms and spinners (physics-driven so characters ride them) ----------
local movers = {}

local function prepare(part)
	local origin = part.CFrame
	part.Anchored = false
	local attachment = Instance.new("Attachment")
	attachment.Parent = part
	local align = Instance.new("AlignPosition")
	align.Mode = Enum.PositionAlignmentMode.OneAttachment
	align.Attachment0 = attachment
	align.RigidityEnabled = true
	align.Position = origin.Position
	align.Parent = part
	local orient = Instance.new("AlignOrientation")
	orient.Mode = Enum.OrientationAlignmentMode.OneAttachment
	orient.Attachment0 = attachment
	orient.RigidityEnabled = true
	orient.CFrame = origin.Rotation
	orient.Parent = part
	pcall(function() part:SetNetworkOwner(nil) end)
	return origin, align, orient
end

for _, part in ipairs(CollectionService:GetTagged("BloxMove")) do
	local args = numbers(tagArg(part, "BloxMoveArgs="))
	local offset = Vector3.new(args[1] or 0, args[2] or 0, args[3] or 0)
	local duration = math.max(0.2, args[4] or 3)
	local origin, align = prepare(part)
	table.insert(movers, function(t)
		local alpha = 0.5 - 0.5 * math.cos(math.pi * t / duration)
		align.Position = origin.Position + offset * alpha
	end)
end

for _, part in ipairs(CollectionService:GetTagged("BloxSpin")) do
	local speed = tonumber(tagArg(part, "BloxSpinSpeed=")) or 1.5
	local origin, _, orient = prepare(part)
	table.insert(movers, function(t)
		orient.CFrame = CFrame.Angles(0, speed * t, 0) * origin.Rotation
	end)
end

local clock = 0
RunService.Heartbeat:Connect(function(dt)
	clock += dt
	for _, update in ipairs(movers) do update(clock) end
end)
`;

/**
 * Client-side Luau runtime injected into StarterPlayer/StarterPlayerScripts/BloxClient.
 * Jump pads must run on the client because the character's physics is client-owned.
 */
export const BLOX_CLIENT_RUNTIME = `-- BloxClient · generated by Blox Studio. Powers jump pads (character physics is client-owned).
local CollectionService = game:GetService("CollectionService")
local Players = game:GetService("Players")
local player = Players.LocalPlayer
local cooldown = false

local function power(part)
	for _, tag in ipairs(CollectionService:GetTags(part)) do
		if string.sub(tag, 1, 9) == "BloxJump=" then
			return tonumber(string.sub(tag, 10)) or 100
		end
	end
	return 100
end

local function hook(part)
	part.Touched:Connect(function(hit)
		local character = player.Character
		if cooldown or not character or not hit:IsDescendantOf(character) then return end
		local root = character:FindFirstChild("HumanoidRootPart")
		local humanoid = character:FindFirstChildOfClass("Humanoid")
		if not root or not humanoid then return end
		cooldown = true
		humanoid:ChangeState(Enum.HumanoidStateType.Jumping)
		local v = root.AssemblyLinearVelocity
		root.AssemblyLinearVelocity = Vector3.new(v.X, power(part), v.Z)
		task.delay(0.35, function() cooldown = false end)
	end)
end

for _, part in ipairs(CollectionService:GetTagged("BloxJumpPad")) do hook(part) end
CollectionService:GetInstanceAddedSignal("BloxJumpPad"):Connect(hook)
`;
