/**
 * The Sky Islands obby's rules, written as ordinary scripts (so they show up in the Explorer and can be edited).
 * Both scripts do nothing unless the Workspace attribute `ScriptedGameplay` is true, which only VoxMesa's Play mode sets.
 */

/** Script in ServerScriptService: kill bricks, checkpoints, finish line and jump pads. */
export const OBBY_RULES_SOURCE = [
  '-- ObbyRules: the rules of this obstacle course, as a script you can change.',
  '-- Each part\'s setting (Properties > Gameplay) shows up here as an attribute:',
  '--   Behavior = "kill" | "checkpoint" | "finish" | "jumpPad"',
  '-- Delete this script and those rules stop working.',
  'if workspace:GetAttribute("ScriptedGameplay") ~= true then return end',
  '',
  'local Players = game:GetService("Players")',
  'local ReplicatedStorage = game:GetService("ReplicatedStorage")',
  '',
  'local JUMP_PAD_COOLDOWN = 0.4 -- seconds between bounces',
  '',
  '-- The server tells the player\'s screen what happened through this event (see ObbyClient).',
  'local notify = Instance.new("RemoteEvent")',
  'notify.Name = "Notify"',
  'notify.Parent = ReplicatedStorage',
  '',
  'local state = {} -- player -> { stage, checkpoint, startedAt, finished }',
  '',
  'Players.PlayerAdded:Connect(function(player)',
  '\tlocal stats = Instance.new("Folder")',
  '\tstats.Name = "leaderstats"',
  '\tstats.Parent = player',
  '\tlocal stage = Instance.new("IntValue")',
  '\tstage.Name = "Stage"',
  '\tstage.Value = 1',
  '\tstage.Parent = stats',
  '',
  '\tlocal s = { stage = stage, checkpoint = nil, startedAt = os.clock(), finished = false }',
  '\tstate[player] = s',
  '',
  '\t-- After dying, start again from the last checkpoint.',
  '\tplayer.CharacterAdded:Connect(function(character)',
  '\t\tif s.checkpoint then',
  '\t\t\tcharacter.HumanoidRootPart.CFrame = CFrame.new(s.checkpoint.X, s.checkpoint.Y, s.checkpoint.Z)',
  '\t\tend',
  '\tend)',
  'end)',
  '',
  'local function playerFrom(hit)',
  '\treturn Players:GetPlayerFromCharacter(hit.Parent)',
  'end',
  '',
  'for _, part in ipairs(workspace:GetDescendants()) do',
  '\tlocal behavior = part:GetAttribute("Behavior")',
  '',
  '\tif behavior == "kill" then',
  '\t\tpart.Touched:Connect(function(hit)',
  '\t\t\tlocal humanoid = hit.Parent:FindFirstChildOfClass("Humanoid")',
  '\t\t\tif humanoid then humanoid.Health = 0 end',
  '\t\tend)',
  '',
  '\telseif behavior == "checkpoint" then',
  '\t\tlocal number = part:GetAttribute("Checkpoint") or 2',
  '\t\tpart.Touched:Connect(function(hit)',
  '\t\t\tlocal player = playerFrom(hit)',
  '\t\t\tlocal s = player and state[player]',
  '\t\t\tif s and number > s.stage.Value then',
  '\t\t\t\ts.stage.Value = number',
  '\t\t\t\ts.checkpoint = Vector3.new(part.Position.X, part.Position.Y + part.Size.Y / 2 + 2.7, part.Position.Z)',
  '\t\t\t\tnotify:FireClient(player, "Checkpoint!", "Stage " .. number)',
  '\t\t\tend',
  '\t\tend)',
  '',
  '\telseif behavior == "finish" then',
  '\t\tpart.Touched:Connect(function(hit)',
  '\t\t\tlocal player = playerFrom(hit)',
  '\t\t\tlocal s = player and state[player]',
  '\t\t\tif s and not s.finished then',
  '\t\t\t\ts.finished = true',
  '\t\t\t\tnotify:FireClient(player, "You beat the obby!", string.format("Time: %.1f seconds", os.clock() - s.startedAt))',
  '\t\t\tend',
  '\t\tend)',
  '',
  '\telseif behavior == "jumpPad" then',
  '\t\tlocal power = part:GetAttribute("JumpPower") or 100',
  '\t\tlocal lastBounce = 0',
  '\t\tpart.Touched:Connect(function(hit)',
  '\t\t\tif os.clock() - lastBounce < JUMP_PAD_COOLDOWN then return end',
  '\t\t\tlastBounce = os.clock()',
  '\t\t\thit.AssemblyLinearVelocity = Vector3.new(0, power, 0)',
  '\t\tend)',
  '\tend',
  'end',
  '',
].join('\n');

/** LocalScript in StarterPlayerScripts: shows what the server sends as a notification. */
export const OBBY_CLIENT_SOURCE = [
  '-- ObbyClient: runs on the player\'s device and shows the messages ObbyRules sends.',
  'if workspace:GetAttribute("ScriptedGameplay") ~= true then return end',
  '',
  'local ReplicatedStorage = game:GetService("ReplicatedStorage")',
  'local StarterGui = game:GetService("StarterGui")',
  '',
  'local notify = ReplicatedStorage:WaitForChild("Notify")',
  'notify.OnClientEvent:Connect(function(title, text)',
  '\tStarterGui:SetCore("SendNotification", { Title = title, Text = text, Duration = 4 })',
  'end)',
  '',
].join('\n');
